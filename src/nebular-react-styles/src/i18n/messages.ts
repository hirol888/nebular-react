/**
 * Flat message catalog used by the shared locale provider.
 * Keys are namespaced by component (`dataGrid.undo`, `chat.reply`, ...).
 */
export type NebularMessages = Record<string, string>;

export type NebularMessageParams = Record<string, string | number>;

export const DEFAULT_UI_LOCALE = 'en-US';

export function formatNebularMessage(template: string, params?: NebularMessageParams): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = params[key];

    return value === undefined ? match : String(value);
  });
}

