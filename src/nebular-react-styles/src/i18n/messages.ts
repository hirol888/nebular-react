const catalogs: Record<string, NebularMessages> = {
  'en-us': enUSMessages,
  'pt-br': ptBRMessages
};

export function getNebularLocaleMessages(locale: string): NebularMessages {
  const normalized = String(locale || DEFAULT_UI_LOCALE).toLowerCase();

  if (catalogs[normalized]) {
    return catalogs[normalized];
  }

  const prefix = normalized.split('-')[0];

  if (catalogs[prefix]) {
    return catalogs[prefix];
  }

  return {};
}

